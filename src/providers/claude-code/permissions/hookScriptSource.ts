/**
 * Source of the standalone PreToolUse hook script(s) written to disk at
 * install time. Two variants — POSIX `sh` for macOS/Linux, PowerShell for
 * Windows — because:
 *
 *   1. We can't use Obsidian's `process.execPath` as a Node interpreter:
 *      Obsidian refuses to honor ELECTRON_RUN_AS_NODE unless the user
 *      manually enables "Command line interface" in Settings → Advanced.
 *      Without that, Obsidian prints "Command line interface is not
 *      enabled" to stdout and exits 0 — which the CLI sees as a malformed
 *      hook response and falls back to its default deny path. The user's
 *      tool gets blocked with no UI prompt.
 *
 *   2. We can't depend on a system Node being on PATH: many users don't
 *      have one, especially on Windows.
 *
 * Both scripts:
 *   - read JSON from stdin,
 *   - extract `tool_use_id`,
 *   - write the input atomically to <tmpDir>/hook-<id>.req,
 *   - poll for <tmpDir>/hook-<id>.resp every ~150ms,
 *   - on response: emit the corresponding `hookSpecificOutput` JSON,
 *   - on inner-timeout (OBSIDIAN_CC_HOOK_TIMEOUT_MS, default 5min): emit
 *     `permissionDecision:"deny"` with a "timed out" reason — fail-CLOSED.
 *
 * Inner timeout < CLI's outer timeout is load-bearing for safety: the
 * CLI's outer timeout fails OPEN (the tool runs unsanctioned), so the
 * script must always exit with a decision before that fires.
 */
export const HOOK_SCRIPT_UNIX = `#!/bin/sh
# permissionHook.sh — generated by obsidian-scholion; do not edit by hand.
set -u
INPUT="$(cat)"
TOOL_USE_ID=$(printf '%s' "$INPUT" | sed -n 's/.*"tool_use_id"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p')
emit() {
	if [ -n "\${2:-}" ]; then
		printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"%s","permissionDecisionReason":"%s"}}' "$1" "$2"
	else
		printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"%s"}}' "$1"
	fi
	exit 0
}
[ -z "\${OBSIDIAN_CC_TMP_DIR:-}" ] && emit deny "Plugin tmp dir not provided"
[ -z "$TOOL_USE_ID" ] && emit deny "No tool_use_id"
TMP="$OBSIDIAN_CC_TMP_DIR"
REQ="$TMP/hook-$TOOL_USE_ID.req"
RESP="$TMP/hook-$TOOL_USE_ID.resp"
TIMEOUT_MS="\${OBSIDIAN_CC_HOOK_TIMEOUT_MS:-300000}"
TIMEOUT_S=$((TIMEOUT_MS / 1000))
printf '%s' "$INPUT" > "$REQ.tmp" && mv "$REQ.tmp" "$REQ" || emit deny "Could not write request file"
START=$(date +%s)
DEADLINE=$((START + TIMEOUT_S))
while [ ! -f "$RESP" ]; do
	NOW=$(date +%s)
	if [ "$NOW" -ge "$DEADLINE" ]; then
		rm -f "$REQ"
		emit deny "Permission prompt timed out (no user response)."
	fi
	sleep 0.15
done
RESP_TEXT="$(cat "$RESP" 2>/dev/null || true)"
rm -f "$REQ" "$RESP"
DECISION=$(printf '%s' "$RESP_TEXT" | sed -n 's/.*"decision"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p')
REASON=$(printf '%s' "$RESP_TEXT" | sed -n 's/.*"reason"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p')
[ -z "$DECISION" ] && DECISION=deny
emit "$DECISION" "$REASON"
`;

export const HOOK_SCRIPT_WINDOWS = `# permissionHook.ps1 — generated by obsidian-scholion; do not edit by hand.
$ErrorActionPreference = 'Stop'
$Input = [Console]::In.ReadToEnd()
function Emit($decision, $reason) {
	if ($reason) {
		$out = '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"' + $decision + '","permissionDecisionReason":"' + $reason + '"}}'
	} else {
		$out = '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"' + $decision + '"}}'
	}
	[Console]::Out.Write($out)
	exit 0
}
$tmp = $env:OBSIDIAN_CC_TMP_DIR
if (-not $tmp) { Emit 'deny' 'Plugin tmp dir not provided' }
$timeoutMs = [int]($env:OBSIDIAN_CC_HOOK_TIMEOUT_MS); if ($timeoutMs -le 0) { $timeoutMs = 300000 }
$idMatch = [regex]::Match($Input, '"tool_use_id"\\s*:\\s*"([^"]+)"')
if (-not $idMatch.Success) { Emit 'deny' 'No tool_use_id' }
$id = $idMatch.Groups[1].Value
$req = Join-Path $tmp ('hook-' + $id + '.req')
$resp = Join-Path $tmp ('hook-' + $id + '.resp')
try {
	[System.IO.File]::WriteAllText("$req.tmp", $Input)
	Move-Item -Force "$req.tmp" $req
} catch { Emit 'deny' 'Could not write request file' }
$deadline = (Get-Date).AddMilliseconds($timeoutMs)
while (-not (Test-Path $resp)) {
	if ((Get-Date) -ge $deadline) {
		Remove-Item -Force -ErrorAction SilentlyContinue $req
		Emit 'deny' 'Permission prompt timed out (no user response).'
	}
	Start-Sleep -Milliseconds 150
}
$respText = Get-Content -Raw $resp -ErrorAction SilentlyContinue
Remove-Item -Force -ErrorAction SilentlyContinue $req
Remove-Item -Force -ErrorAction SilentlyContinue $resp
$dMatch = [regex]::Match($respText, '"decision"\\s*:\\s*"([^"]+)"')
$rMatch = [regex]::Match($respText, '"reason"\\s*:\\s*"([^"]+)"')
$decision = if ($dMatch.Success) { $dMatch.Groups[1].Value } else { 'deny' }
$reason = if ($rMatch.Success) { $rMatch.Groups[1].Value } else { '' }
Emit $decision $reason
`;
